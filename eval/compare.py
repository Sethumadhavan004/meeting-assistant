"""
compare.py - baseline vs a later round, per model, split into seen and held-out meetings.

Seen = m01-m08: the meetings whose baseline failures the round-2 prompt was written after.
Held-out = m09-m10: written after the prompt, never used to shape it. A gain that shows up only
on seen meetings may be overfitting; a gain on both is more likely real.

Usage:  python eval/compare.py            (baseline vs r2, writes eval/03b-round2-results.md)
"""
import argparse
import pathlib

from report import NAME, ROOT, load, med, pooled, tta

SPLITS = [("seen (m01–m08)", {f"m0{i}" for i in range(1, 9)}), ("held-out (m09–m10)", {"m09", "m10"})]


def f2(x):
    return "–" if x != x else f"{x:.2f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--round", default="r2")
    ap.add_argument("--out", default=ROOT / "eval" / "03b-round2-results.md")
    a = ap.parse_args()

    sources = {
        "baseline": (load(ROOT / "scores.csv"), {r["run_id"]: r for r in load(ROOT / "runs.csv")}),
        "system prompt": (load(ROOT / f"scores-{a.round}.csv"), {r["run_id"]: r for r in load(ROOT / f"runs-{a.round}.csv")}),
    }

    L = ["# 03b · Round 2 results: system prompt vs baseline", "",
         f"_Generated by `eval/compare.py` from `scores.csv`/`runs.csv` (baseline) and "
         f"`scores-{a.round}.csv`/`runs-{a.round}.csv` (system prompt). Thinking off for every run. "
         "Tables only; do not edit by hand._", "",
         "**Format is not comparable across rounds:** the baseline counted a line valid if a person could "
         "read it; round 2 requires every line to parse as `owner | task | deadline` with nothing else.", ""]

    for split, meetings in SPLITS:
        L += [f"## {split}", "",
              "| model | prompt | recall | precision | owner | deadline | invented deadlines | "
              "contradicting duplicates | ambiguity | format valid | median time-to-answer s | median output tok |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for m in ("granite", "phi", "bonsai"):
            for label, (scores, runs) in sources.items():
                sc = [s for s in scores if s["model"] == m and s["thinking"] == "off" and s["prompt_id"] in meetings]
                if not sc:
                    continue
                p = pooled(sc)
                rr = [runs[s["run_id"]] for s in sc]
                L.append(f"| {NAME[m]} | {label} | {f2(p['recall'])} ({p['matched']}/{p['gold']}) | {f2(p['precision'])} | "
                         f"{f2(p['owner'])} | {f2(p['deadline'])} | {p['invented']} | {p['contra']} | "
                         f"{f2(p['ambiguity'])} | {p['format']}/{p['n']} | {med([tta(r) for r in rr]):.0f} | "
                         f"{med([int(r['out_tok']) for r in rr]):.0f} |")
        L.append("")

    pathlib.Path(a.out).write_text("\n".join(L), encoding="utf-8")
    print(f"Wrote {a.out}")


if __name__ == "__main__":
    main()
