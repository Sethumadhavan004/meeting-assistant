"""
score.py - turn hand labels into metrics, exactly as defined in eval/02-protocol.md.

Inputs (all hand-checked, never generated by a model):
  ../../gold.md   gold items per meeting (owner UNASSIGNED / deadline NONE matter)
  labels.csv      one row per extracted item: label, gold #, owner_ok, deadline_ok
  runs.csv        one row per run: format_valid

Output:
  ../../scores.csv  one row per run

Usage:  python eval/scoring/score.py
Change a label in labels.csv, re-run, and every number updates.
"""
import argparse
import csv
import pathlib
import re

HERE = pathlib.Path(__file__).parent
ROOT = HERE.parent.parent


def load_gold():
    """meeting id (e.g. 'm01') -> {item #: (owner, deadline)}"""
    gold, cur = {}, None
    for line in (ROOT / "gold.md").read_text(encoding="utf-8").splitlines():
        m = re.match(r"^## (m\d\d)_", line)
        if m:
            cur = m.group(1)
            gold[cur] = {}
            continue
        m = re.match(r"^\|\s*(\d+)\s*\|([^|]*)\|([^|]*)\|([^|]*)\|", line)
        if cur and m:
            gold[cur][int(m.group(1))] = (m.group(2).strip(), m.group(4).strip())
    return gold


def ratio(a, b):
    return round(a / b, 3) if b else ""


def main():
    # --dir r2 scores a later round from eval/scoring/r2/ into scores-r2.csv; default = baseline
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", help="round folder inside eval/scoring, e.g. r2")
    a = ap.parse_args()
    src = HERE / a.dir if a.dir else HERE
    out_path = ROOT / (f"scores-{a.dir}.csv" if a.dir else "scores.csv")

    gold = load_gold()
    labels = list(csv.DictReader((src / "labels.csv").open(encoding="utf-8")))
    runs = list(csv.DictReader((src / "runs.csv").open(encoding="utf-8")))

    out = []
    for run in runs:
        rid = run["run_id"]
        model, think, meeting = rid.split("_")[:3]
        g = gold[meeting]
        unassigned = {n for n, (owner, _) in g.items() if owner == "UNASSIGNED"}
        no_deadline = {n for n, (_, dl) in g.items() if dl == "NONE"}

        rows = [r for r in labels if r["run_id"] == rid]
        matched = {}  # gold # -> first matched label row
        for r in rows:
            if r["label"] == "matched" and int(r["gold"]) not in matched:
                matched[int(r["gold"])] = r
        wrong = sum(r["label"] == "wrong" for r in rows)
        contra = sum(r["label"] == "duplicate" and r["owner_ok"] == "0" for r in rows)

        owners_ok = sum(r["owner_ok"] == "1" for r in matched.values())
        deadlines_ok = sum(r["deadline_ok"] == "1" for r in matched.values())
        invented_dl = sum(1 for n, r in matched.items() if n in no_deadline and r["deadline_ok"] == "0")
        amb = [(2 if matched[n]["owner_ok"] == "1" else 0) if n in matched else 1 for n in unassigned]

        out.append({
            "run_id": rid, "model": model, "thinking": think, "prompt_id": meeting,
            "gold_items": len(g), "matched": len(matched), "wrong": wrong,
            "contradicting_dups": contra,
            "recall": ratio(len(matched), len(g)),
            "precision": ratio(len(matched), len(matched) + wrong) if matched or wrong else "",
            "owner_acc": ratio(owners_ok, len(matched)),
            "deadline_acc": ratio(deadlines_ok, len(matched)),
            "invented_deadlines": invented_dl,
            "ambiguity": round(sum(amb) / len(amb), 2) if amb else "",
            "format_valid": run["format_valid"],
            "review_flags": sum(r["review"] == "REVIEW" for r in rows) + (run["review"] == "REVIEW"),
        })

    with out_path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(out[0]))
        w.writeheader()
        w.writerows(out)
    print(f"Wrote {len(out)} rows to {out_path.name}")


if __name__ == "__main__":
    main()
